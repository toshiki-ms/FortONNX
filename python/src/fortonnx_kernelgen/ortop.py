"""Generated kernels as ONNX Runtime custom operators.

A program that runs its graphs through ONNX Runtime (FortONNX: ``load(..., custom_op_library=...)``) keeps doing so:
the kernels come in as a custom operator library, and the program has no code for any particular graph.

For every kernel NAME the library defines the operator ``fortonnx.kernel::NAME`` of the CUDA provider:

  input 0     the rows [n, ...] in the shape of the original graph's input, FP32, on the device
  input 1     the kernel's constants, UINT32 [words]: a constant of the graph, read on the host when the session is
              created and copied to the device once
  attribute   ``signature``: the signature of the kernel the constants were written for; a library whose kernel has
              another signature refuses the graph when the session is created
  output      [n, ...] in the shape of the original graph's output, FP32, on the device, computed on ONNX
              Runtime's stream

``wrap_graph`` writes the model that uses the operator. Its main graph is that one node. The model also defines the
operator as an ONNX function whose body is the original graph of standard operators, so a session that does not
register the library runs the original graph.
"""

from __future__ import annotations

import numpy as np
import onnx
from onnx import helper, numpy_helper

from .rowgraph import UnsupportedGraph

DOMAIN = "fortonnx.kernel"


def wrap_graph(model: onnx.ModelProto, name: str, constants: np.ndarray, signature: str) -> onnx.ModelProto:
    """The model whose main graph is the node ``fortonnx.kernel::name`` and whose function of that name is the graph
    of ``model``."""
    graph = model.graph
    if model.functions:
        raise UnsupportedGraph("the model already defines functions")
    initializer_names = {tensor.name for tensor in graph.initializer}
    graph_inputs = [value for value in graph.input if value.name not in initializer_names]
    produced = {output for node in graph.node for output in node.output}
    if graph.output[0].name not in produced:
        raise UnsupportedGraph("the output of the graph is its input or a constant: no node computes it")
    used = produced | initializer_names | {value.name for value in graph.input}
    constants_name = f"{name}.constants"
    while constants_name in used:   # a name of the graph must not capture the kernel's constants
        constants_name += "_"
    inputs = [graph_inputs[0].name, constants_name]
    outputs = [graph.output[0].name]
    body = [helper.make_node("Constant", [], [tensor.name], value=tensor) for tensor in graph.initializer]
    body += list(graph.node)
    function = helper.make_function(DOMAIN, name, inputs, outputs, body, opset_imports=list(model.opset_import),
                                    attributes=["signature"])
    node = helper.make_node(name, inputs, outputs, domain=DOMAIN, name=f"{name}_kernel", signature=signature)
    constant_tensor = numpy_helper.from_array(np.ascontiguousarray(constants, dtype=np.uint32), constants_name)
    main = helper.make_graph([node], graph.name, graph_inputs, list(graph.output), initializer=[constant_tensor])
    wrapped = helper.make_model(main, opset_imports=list(model.opset_import) + [helper.make_opsetid(DOMAIN, 1)],
                                functions=[function], ir_version=model.ir_version, producer_name=model.producer_name,
                                producer_version=model.producer_version)
    wrapped.metadata_props.extend(model.metadata_props)
    onnx.checker.check_model(wrapped)
    return wrapped


def operator_library_source(kernels: list) -> str:
    """C++ source of the custom operator library for ``kernels`` (objects with ``name``, ``input_shape`` and
    ``output_shape`` of one row; compile with the ONNX Runtime headers and link with the kernels' objects into one
    shared library)."""
    names = [kernel.name for kernel in kernels]
    if len({name.lower() for name in names}) != len(names):
        raise ValueError(f"kernel names must differ, also without regard to case: {names}")
    includes = "\n".join(f'#include "{name}.h"' for name in names)
    dims = lambda shape: "{" + ", ".join(str(int(d)) for d in shape) + "}"
    shapes = "\n".join(
        f"const std::vector<int64_t> kInputShape_{kernel.name} = {dims(kernel.input_shape)};\n"
        f"const std::vector<int64_t> kOutputShape_{kernel.name} = {dims(kernel.output_shape)};" for kernel in kernels)
    table = "\n".join(
        f'    {{"{name}", &kInputShape_{name}, &kOutputShape_{name}, {name}_create, {name}_run, {name}_destroy}},'
        for name in names)
    operators = ", ".join(f"RowOp(&kKernels[{index}])" for index in range(len(names)))
    return f"""// Generated by fortonnx_kernelgen. Do not edit.
// ONNX Runtime custom operators {DOMAIN}::NAME of the CUDA provider for the generated kernels
// {", ".join(names)}.
// Inputs: 0 the rows [n, ...] on the device; 1 the kernel's constants, UINT32 [words], a constant of the graph (read
// on the host when the session is created). Attribute: signature. Output: [n, ...] on the device, computed on
// ONNX Runtime's stream. The graphs written with the kernels define each operator also as an ONNX function of
// standard operators, which a session without this library runs.
#define ORT_API_MANUAL_INIT
#include "onnxruntime_cxx_api.h"
#undef ORT_API_MANUAL_INIT
#include <cstdint>
#include <mutex>
#include <string>
#include <vector>

{includes}

namespace {{

{shapes}

struct KernelApi {{
  const char* name;
  const std::vector<int64_t>* input_shape;    // of one row
  const std::vector<int64_t>* output_shape;
  int (*create)(const void* constants, size_t words, const char* signature, void** kernel);
  int (*run)(void* kernel, const float* rows, float* outputs, long long row_count, void* stream);
  void (*destroy)(void* kernel);
}};

const KernelApi kKernels[] = {{
{table}
}};

OrtStatusPtr error(const KernelApi* api, const std::string& message) {{
  return Ort::Status(("{DOMAIN}::" + std::string(api->name) + ": " + message).c_str(), ORT_FAIL).release();
}}

struct RowKernel {{
  const KernelApi* api = nullptr;
  void* kernel = nullptr;
  ~RowKernel() {{ api->destroy(kernel); }}

  OrtStatusPtr ComputeV2(OrtKernelContext* context) {{
    try {{
      Ort::KernelContext ctx(context);
      Ort::ConstValue rows = ctx.GetInput(0);
      const std::vector<int64_t> shape = rows.GetTensorTypeAndShapeInfo().GetShape();
      if (shape.empty() || std::vector<int64_t>(shape.begin() + 1, shape.end()) != *api->input_shape)
        return error(api, "the rows have another shape");
      std::vector<int64_t> out_shape{{shape[0]}};
      out_shape.insert(out_shape.end(), api->output_shape->begin(), api->output_shape->end());
      Ort::UnownedValue out = ctx.GetOutput(0, out_shape);
      const int code = api->run(kernel, rows.GetTensorData<float>(), out.GetTensorMutableData<float>(), shape[0],
                                ctx.GetGPUComputeStream());
      if (code != 0) return error(api, "kernel launch failed (CUDA error " + std::to_string(code) + ")");
      return nullptr;
    }} catch (const Ort::Exception& e) {{
      return Ort::Status(e).release();
    }}
  }}
}};

struct RowOp : Ort::CustomOpBase<RowOp, RowKernel, true> {{
  explicit RowOp(const KernelApi* api) : api(api) {{}}

  OrtStatusPtr CreateKernelV2(const OrtApi&, const OrtKernelInfo* kernel_info, void** kernel) const {{
    try {{
      const Ort::ConstKernelInfo info(kernel_info);
      if (info.GetInputCount() != 2) return error(api, "the node takes the rows and the constants");
      int constant = 0;
      Ort::ConstValue value = info.GetTensorConstantInput(1, &constant);
      if (!constant) return error(api, "the constants are not a constant of the graph");
      const auto shape = value.GetTensorTypeAndShapeInfo();
      if (shape.GetElementType() != ONNX_TENSOR_ELEMENT_DATA_TYPE_UINT32) return error(api, "the constants are not UINT32");
      if (value.GetTensorMemoryInfo().GetDeviceType() != OrtMemoryInfoDeviceType_CPU)
        return error(api, "the constants are not on the host");
      const std::string signature = info.GetAttribute<std::string>("signature");
      void* handle = nullptr;
      const int code = api->create(value.GetTensorData<uint32_t>(), shape.GetElementCount(), signature.c_str(), &handle);
      if (code != 0)
        return error(api, "the graph's constants were written for another kernel (signature " + signature +
                              "), or the device refused them (CUDA error " + std::to_string(code) + ")");
      RowKernel* row_kernel = new RowKernel;
      row_kernel->api = api;
      row_kernel->kernel = handle;
      *kernel = row_kernel;
      return nullptr;
    }} catch (const Ort::Exception& e) {{
      return Ort::Status(e).release();
    }}
  }}
  const char* GetName() const {{ return api->name; }}
  const char* GetExecutionProviderType() const {{ return "CUDAExecutionProvider"; }}
  size_t GetInputTypeCount() const {{ return 2; }}
  ONNXTensorElementDataType GetInputType(size_t index) const {{
    return index == 0 ? ONNX_TENSOR_ELEMENT_DATA_TYPE_FLOAT : ONNX_TENSOR_ELEMENT_DATA_TYPE_UINT32;
  }}
  OrtMemType GetInputMemoryType(size_t index) const {{ return index == 0 ? OrtMemTypeDefault : OrtMemTypeCPUInput; }}
  size_t GetOutputTypeCount() const {{ return 1; }}
  ONNXTensorElementDataType GetOutputType(size_t) const {{ return ONNX_TENSOR_ELEMENT_DATA_TYPE_FLOAT; }}

  const KernelApi* api;
}};

}}  // namespace

// The one function the library exports (the build hides every other symbol).
extern "C" __attribute__((visibility("default"))) OrtStatus* ORT_API_CALL RegisterCustomOps(
    OrtSessionOptions* options, const OrtApiBase* api_base) {{
  Ort::InitApi(api_base->GetApi(ORT_API_VERSION));
  static RowOp operators[] = {{{operators}}};
  static Ort::CustomOpDomain domain{{"{DOMAIN}"}};
  static std::once_flag added;   // sessions may be created from several threads
  std::call_once(added, [] {{
    for (RowOp& op : operators) domain.Add(&op);
  }});
  Ort::UnownedSessionOptions(options).Add(domain);
  return nullptr;
}}
"""


def build_script(names: list[str], architecture: str = "sm_90", direct: list[str] | None = None) -> str:
    """Shell script that builds the library of the kernels from the generated sources of one directory: the custom
    operators of ONNX Runtime and the direct entry (``direct``: the names of its functions, direct.entry_names).
    ``architecture`` is the default GPU architecture (kernels on the tensor cores need sm_90a)."""
    direct = direct or []
    exported = " ".join(f"{name};" for name in ["RegisterCustomOps"] + direct)
    return f"""#!/bin/sh
# Generated by fortonnx_kernelgen: builds the custom operator library of the kernels {" ".join(names)}.
# usage: sh build.sh ORT_INCLUDE [ARCH] [LIBRARY]
#   ORT_INCLUDE  directory of onnxruntime_cxx_api.h
#   ARCH         GPU architecture of nvcc (default {architecture})
#   LIBRARY      file name of the library (default libfortonnx_kernels.so)
# --fmad=false keeps the products and sums of the graph's elementwise operators separate operations. The library
# links the CUDA runtime statically (nvcc's default) and exports RegisterCustomOps (for ONNX Runtime) and the direct
# entry ({" ".join(direct) or "none"}) only.
set -eu
include=$(cd "$1" && pwd)
arch=${{2:-{architecture}}}
library=${{3:-libfortonnx_kernels.so}}
cd "$(dirname "$0")"
for name in {" ".join(names)}; do
  nvcc -O3 -std=c++17 -gencode "arch=compute_${{arch#sm_}},code=$arch" --fmad=false \\
    -Xcompiler -fPIC -Xcompiler -fvisibility=hidden -c "$name.cu" -o "$name.o"
done
g++ -O2 -std=c++17 -fPIC -fvisibility=hidden -fvisibility-inlines-hidden -I"$include" -I. -c kernel_ops.cc -o kernel_ops.o
g++ -O2 -std=c++17 -fPIC -fvisibility=hidden -fvisibility-inlines-hidden -I. -c kernel_direct.cc -o kernel_direct.o
printf '{{ global: {exported} local: *; }};\n' > exports.map
nvcc -shared -Xlinker --version-script=exports.map -o "$library" kernel_ops.o kernel_direct.o {" ".join(name + ".o" for name in names)}
"""
